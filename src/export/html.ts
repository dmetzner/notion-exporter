export async function writeHtml(
  htmlDir: string,
  doc: { id: string; title: string; fallbackTitle?: string },
  markdown: string,
  subdir = "",
  opts: {
    archiveTitle?: string;
    archiveIcon?: string;
    favicon?: { kind: "emoji" | "image"; value: string };
    pageTitleHtml?: string;
    styleBackLinks?: boolean;
  } = {},
): Promise<string> {
  const filename = `${safeSegment(doc.title)}.${doc.id}.html`;
  const abs = path.join(htmlDir, subdir, filename);
  await fsp.mkdir(path.dirname(abs), { recursive: true });
  const title = doc.title || doc.fallbackTitle || "(untitled)";
  await fsp.writeFile(
    abs,
    renderHtml(title, markdown, {
      assetPrefix: assetPrefix(subdir),
      indexPrefix: indexPrefix(subdir),
      archiveTitle: opts.archiveTitle,
      archiveIcon: opts.archiveIcon,
      favicon: opts.favicon,
      pageTitleHtml: opts.pageTitleHtml,
      styleBackLinks: opts.styleBackLinks,
    }),
  );
  return abs;
}

export async function writeStylesheet(htmlDir: string): Promise<string> {
  const abs = path.join(htmlDir, STYLE_FILENAME);
  await fsp.writeFile(abs, STYLE_CSS);
  return abs;
}

