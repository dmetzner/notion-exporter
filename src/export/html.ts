export interface SitemapIcon {
  kind: "emoji" | "image";
  // emoji char OR export-root-relative asset path (e.g. "assets/abc.png")
  value: string;
}

export interface SitemapEntry {
  id: string;
  title: string;
  href: string;
  kind: "page" | "database";
  parentId?: string;
  icon?: SitemapIcon;
  /** Position within parent (Notion's child_page order). Lower = earlier.
   * When unset, the tree falls back to alphabetical sort. */
  position?: number;
  /** Pre-rendered HTML title (e.g. `:rocket:` swapped for an `<img>`). Uses
   * root-relative `assets/<hash>.…` paths so injectSidebars can rewrite
   * them to per-page-depth-relative paths. */
  titleHtml?: string;
}

interface TreeNode {
  id: string;
  title: string;
  titleHtml?: string;
  href: string;
  kind: "page" | "database";
  icon?: SitemapIcon;
  position?: number;
  children: TreeNode[];
}

function buildTree(entries: SitemapEntry[]): TreeNode[] {
  return buildTreeWithParents(entries).roots;
}

interface BuiltTree {
  roots: TreeNode[];
  /** child id → parent id (undefined for roots present in entries). */
  parentOf: Map<string, string | undefined>;
}

function buildTreeWithParents(entries: SitemapEntry[]): BuiltTree {
  const byId = new Map<string, TreeNode>();
  const parentOf = new Map<string, string | undefined>();
  for (const e of entries) {
    byId.set(e.id, {
      id: e.id,
      title: e.title,
      ...(e.titleHtml ? { titleHtml: e.titleHtml } : {}),
      href: e.href,
      kind: e.kind,
      icon: e.icon,
      ...(typeof e.position === "number" ? { position: e.position } : {}),
      children: [],
    });
  }
  const roots: TreeNode[] = [];
  for (const e of entries) {
    const node = byId.get(e.id)!;
    if (e.parentId && byId.has(e.parentId)) {
      byId.get(e.parentId)!.children.push(node);
      parentOf.set(e.id, e.parentId);
    } else {
      roots.push(node);
      parentOf.set(e.id, undefined);
    }
  }
  // Sort children by their Notion-supplied `position` when present, falling
  // back to alphabetical for entries we couldn't position (top-level + any
  // page whose parent's child_page blocks didn't surface its id).
  const sortRec = (n: TreeNode[]) => {
    n.sort((a, b) => {
      const ap = typeof a.position === "number" ? a.position : Number.POSITIVE_INFINITY;
      const bp = typeof b.position === "number" ? b.position : Number.POSITIVE_INFINITY;
      if (ap !== bp) return ap - bp;
      return a.title.localeCompare(b.title);
    });
    for (const x of n) sortRec(x.children);
  };
  sortRec(roots);
  return { roots, parentOf };
}

function iconHtml(node: TreeNode, prefix: string): string {
  if (node.icon?.kind === "emoji") {
    return `<span class="tree-emoji" aria-hidden="true">${htmlEscape(node.icon.value)}</span>`;
  }
  if (node.icon?.kind === "image") {
    // Normalize Windows "\" separators in the (relative) icon path to "/".
    const value = node.icon.value.replace(/\\/g, "/");
    return `<img class="tree-icon" src="${prefix}${htmlEscape(value)}" alt="" loading="lazy">`;
  }
  const fallback = node.kind === "database" ? "🗂" : "📄";
  return `<span class="tree-emoji tree-fallback" aria-hidden="true">${fallback}</span>`;
}

// Branch toggle uses a hidden checkbox + label so the chevron and the page link have
// independent hit targets — clicking the chevron expands/collapses, clicking the title
// navigates. No JS needed.
//
// `ancestors`, when provided, is the precomputed Set of node ids on the
// path from the current page up to the root (inclusive of the current page).
// Lookups are O(1) — replaces the old O(N²) `containsId` walk.
function renderBranches(
  nodes: TreeNode[],
  opts: { prefix: string; currentId?: string; idScope: string; ancestors?: Set<string> },
): string {
  if (nodes.length === 0) return "";
  return `<ul class="tree">${renderItems(nodes, opts)}</ul>`;
}

// Emit just the `<li>`s for a list of tree nodes — no surrounding `<ul>`.
// Callers wrap the result in `<ul class="tree">` (top-level) or
// `<ul class="children">` (nested). Keeping the `<ul>` outside this function
// avoids `<ul class="children"><ul class="tree">…</ul></ul>` chains, which
// are invalid per the HTML5 content model (a `<ul>` may only contain `<li>`s).
function renderItems(
  nodes: TreeNode[],
  opts: { prefix: string; currentId?: string; idScope: string; ancestors?: Set<string> },
): string {
  return nodes
    .map((n) => {
      const hasChildren = n.children.length > 0;
      const isActive = n.id === opts.currentId;
      // Ancestor = node whose subtree contains currentId (but not the node itself).
      // The set contains currentId + all parents, so a non-active hit means
      // "ancestor of current".
      const isAncestor = !isActive && (opts.ancestors?.has(n.id) ?? false);
      const open = isActive || isAncestor;
      const linkClass = isActive ? ' class="active" aria-current="page"' : "";
      const href = `${opts.prefix}${htmlEscape(n.href)}`;
      const icon = iconHtml(n, opts.prefix);
      // titleHtml carries inline imgs whose `src="assets/…"` will be rewritten
      // to the page's depth-relative path below via the same regex that handles
      // body images. Fall back to escaped plain title when no titleHtml.
      const titleInner = n.titleHtml ?? htmlEscape(n.title);
      const title = `<a href="${href}"${linkClass} data-id="${n.id}"><span class="tree-title">${titleInner}</span></a>`;
      if (!hasChildren) {
        return `<li class="leaf"><span class="row"><span class="caret-spacer" aria-hidden="true"></span>${icon}${title}</span></li>`;
      }
      const cid = `${opts.idScope}-${n.id}`;
      const checked = open ? " checked" : "";
      const caret = `<label class="caret" for="${cid}" aria-label="Toggle"><svg viewBox="0 0 12 12" width="12" height="12" aria-hidden="true"><path d="M4 2 L8 6 L4 10" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"/></svg></label>`;
      const inner = renderItems(n.children, opts);
      return `<li class="branch"><input class="branch-toggle" id="${cid}" data-id="${n.id}" type="checkbox" hidden${checked}><span class="row">${caret}${icon}${title}</span><ul class="children">${inner}</ul></li>`;
    })
    .join("");
}

function renderTree(nodes: TreeNode[]): string {
  return renderBranches(nodes, { prefix: "", idScope: "ix" });
}

function renderTreeNav(
  nodes: TreeNode[],
  opts: { prefix: string; currentId?: string; ancestors?: Set<string> },
): string {
  return renderBranches(nodes, { ...opts, idScope: "sb" });
}

/** Mutate a rendered sidebar skeleton to mark the active page and pre-expand
 * each ancestor's `<details>`-style toggle. The skeleton is produced once per
 * depth-bucket with no `active`/`checked` markers; this pass is a single
 * regex replace per page (string-replace is linear in skeleton size, not in
 * the page count, so total cost across N pages is O(N · skeleton bytes)
 * rather than O(N²) re-renders).
 */
function applyActiveMarkers(skeleton: string, ancestors: Set<string>, currentId?: string): string {
  let out = skeleton;
  if (currentId && ancestors.has(currentId)) {
    // Active link: add class + aria-current. There is exactly one match.
    // The skeleton's anchor is emitted by `renderItems` as
    // `<a href="…" data-id="…"…>`. We scan for that fixed prefix, then walk
    // back to find the `href="…"` token so we can rebuild the anchor with
    // the active markers inserted between href and data-id — preserving the
    // original quoting and attribute order without paying for a fresh
    // RegExp compile per page.
    const dataAttr = ` data-id="${currentId}"`;
    const idx = out.indexOf(dataAttr);
    if (idx !== -1) {
      // Walk back to the start of `<a `. Anchors never nest, so the nearest
      // preceding `<a ` is ours.
      const aStart = out.lastIndexOf("<a ", idx);
      if (aStart !== -1) {
        const between = out.slice(aStart + 3, idx); // e.g. `href="Foo.html"`
        const replacement = `<a ${between} class="active" aria-current="page"${dataAttr}`;
        out = out.slice(0, aStart) + replacement + out.slice(idx + dataAttr.length);
      }
    }
  }
  // Pre-expand every <input> on the path. Branch inputs only — leaves don't
  // carry an <input>. Ancestors not in the tree (no <input data-id=>) are
  // silent no-ops. Plain string-needle replace — ~3.8k fewer RegExp
  // constructions per export vs. the old `new RegExp(...)` per ancestor.
  for (const id of ancestors) {
    const needle = `<input class="branch-toggle" id="sb-${id}" data-id="${id}" type="checkbox" hidden>`;
    const i = out.indexOf(needle);
    if (i === -1) continue;
    // Replace just the trailing `>` with ` checked>` — cheaper than
    // re-templating the whole needle.
    out = `${out.slice(0, i + needle.length - 1)} checked>${out.slice(i + needle.length)}`;
  }
  return out;
}

// Page templates are written with a `<!--NE_SIDEBAR-->` placeholder so we don't have to
// know the full sitemap at write time. After all entries are collected, this pass walks
// every emitted HTML file and replaces the placeholder with a tree rooted at htmlDir
// (with active-page highlighting + ancestor branches pre-expanded).
export async function injectSidebars(
  htmlDir: string,
  entries: SitemapEntry[],
  opts: { extraFiles?: string[] } = {},
): Promise<void> {
  const { roots, parentOf } = buildTreeWithParents(entries);

  // Skeleton cache, keyed by depth-prefix (e.g. "", "../", "../../"). Most
  // exports have 1-3 unique depths; tree HTML is identical across pages at
  // the same depth aside from the per-page active/checked markers.
  const skeletonCache = new Map<string, string>();
  const skeletonFor = (prefix: string): string => {
    const cached = skeletonCache.get(prefix);
    if (cached !== undefined) return cached;
    let nav = renderTreeNav(roots, { prefix });
    // Rewrite root-relative `assets/<hash>` URLs (from custom-emoji <img>s
    // embedded in titleHtml) so they walk back out of `html/<subdir>/` to
    // the export root's assets/ dir.
    const assetsPrefix = `${prefix}../`;
    // Match both "assets/" and a Windows-produced "assets\" so custom-emoji
    // <img> srcs in titleHtml get the depth-correct "../assets/" prefix.
    nav = nav.replace(/(src|href)="assets[\\/]/g, `$1="${assetsPrefix}assets/`);
    skeletonCache.set(prefix, nav);
    return nav;
  };

  // Walk parents into a Set once per page. O(depth), not O(N). Memoised by
  // node id — ancestor chains overlap heavily across siblings, so each chain
  // is resolved at most once per export.
  const ancestorCache = new Map<string, Set<string>>();
  const ancestorsFor = (id: string): Set<string> => {
    const cached = ancestorCache.get(id);
    if (cached) return cached;
    const set = new Set<string>();
    let cur: string | undefined = id;
    // Guard against cycles in malformed sitemaps.
    while (cur && !set.has(cur)) {
      set.add(cur);
      cur = parentOf.get(cur);
    }
    ancestorCache.set(id, set);
    return set;
  };

  const pool = createPool(24);
  await Promise.all(
    entries.map((e) =>
      pool.run(async () => {
        const fileAbs = path.join(htmlDir, e.href);
        const dir = path.posix.dirname(e.href.split(path.sep).join("/"));
        const depth = dir === "." || dir === "" ? 0 : dir.split("/").length;
        const prefix = "../".repeat(depth);
        const skeleton = skeletonFor(prefix);
        const nav = applyActiveMarkers(skeleton, ancestorsFor(e.id), e.id);
        let html: string;
        try {
          html = await fsp.readFile(fileAbs, "utf8");
        } catch {
          return;
        }
        if (!html.includes("<!--NE_SIDEBAR-->")) return;
        await fsp.writeFile(fileAbs, html.replace("<!--NE_SIDEBAR-->", nav));
      }),
    ),
  );
  // Extra files (stats.html, etc.) carry the marker but aren't sitemap
  // entries — patch them too with a no-active-id skeleton so the sidebar
  // chrome matches the rest of the export.
  const extras = opts.extraFiles ?? [];
  await Promise.all(
    extras.map((rel) =>
      pool.run(async () => {
        const fileAbs = path.join(htmlDir, rel);
        const dir = path.posix.dirname(rel.split(path.sep).join("/"));
        const depth = dir === "." || dir === "" ? 0 : dir.split("/").length;
        const prefix = "../".repeat(depth);
        const skeleton = skeletonFor(prefix);
        let html: string;
        try {
          html = await fsp.readFile(fileAbs, "utf8");
        } catch {
          return;
        }
        if (!html.includes("<!--NE_SIDEBAR-->")) return;
        await fsp.writeFile(fileAbs, html.replace("<!--NE_SIDEBAR-->", skeleton));
      }),
    ),
  );
}

export async function writeSitemap(
  htmlDir: string,
  entries: SitemapEntry[],
  generatedAt: string,
  opts: { searchIndexPath?: string; archiveTitle?: string; archiveIcon?: string } = {},
): Promise<string> {
  const archiveTitle = opts.archiveTitle ?? "Your Notion archive";
  // The index sits at `html/index.html`; assets/ is at the export root, one
  // level up. Walk back out of html/ to reach it.
  const iconRaw = (opts.archiveIcon ?? "").trim();
  const isIconUrl = /^https?:\/\//i.test(iconRaw);
  const isIconImage =
    !!iconRaw &&
    (isIconUrl || iconRaw.includes("/") || /\.(png|jpg|jpeg|svg|webp|gif)$/i.test(iconRaw));
  const iconSrc = isIconUrl ? iconRaw : iconRaw.startsWith("assets/") ? `../${iconRaw}` : iconRaw;
  const heroIcon = !iconRaw
    ? ""
    : isIconImage
      ? `<img class="index-hero-icon" src="${htmlEscape(iconSrc)}" alt="" loading="lazy">`
      : `<span class="index-hero-emoji" aria-hidden="true">${htmlEscape(iconRaw)}</span>`;
  const favicon = isIconImage
    ? renderFavicon({ kind: "image", value: iconSrc })
    : renderFavicon({ kind: "emoji", value: iconRaw || "📚" });
  const tree = buildTree(entries);
  const counts = {
    pages: entries.filter((e) => e.kind === "page").length,
    dbs: entries.filter((e) => e.kind === "database").length,
  };
  const searchTags = opts.searchIndexPath
    ? `<script src="search.js" defer></script>
<script src="lightbox.js" defer></script>
<!-- Lazy-load lunr.min.js + search-index.js on first interaction. -->
<script>${SEARCH_BOOTSTRAP_JS}window.__NE_BOOT_SEARCH("");</script>`
    : `<script src="lightbox.js" defer></script>`;
  const searchBox = opts.searchIndexPath
    ? `<form class="ne-search" onsubmit="return false">
  <input id="ne-search" data-ne-search type="search" placeholder="Search titles or content…" autocomplete="off">
</form>
<ol id="ne-search-results" class="ne-results" hidden></ol>`
    : "";

  // Format the export timestamp as `YYYY-MM-DD HH:mm` (UTC). The
  // page-footer's `Last edited` / `Exported` strings render plain ISO dates,
  // so use the same format here to stay consistent. ISO is unambiguous
  // regardless of viewer locale and survives in the search index unchanged.
  let formattedDate = generatedAt;
  try {
    const d = new Date(generatedAt);
    if (!Number.isNaN(d.getTime())) {
      const iso = d.toISOString();
      formattedDate = `${iso.slice(0, 10)} ${iso.slice(11, 16)} UTC`;
    }
  } catch {
    // fall through with raw timestamp
  }

  const themeWidget = `<div class="topbar-theme index-theme" role="group" aria-label="Theme">
    ${THEME_BUTTONS}</div>`;

  const body = `<header class="index-hero">
  ${themeWidget}
  <div class="index-hero-row">
    ${heroIcon}
    <div class="index-hero-text">
      <h1>${htmlEscape(archiveTitle)}</h1>
      <p class="lede">A static, offline-readable snapshot of your workspace.</p>
    </div>
  </div>
  <dl class="stats">
    <div><dt>Pages</dt><dd>${counts.pages}</dd></div>
    <div><dt>Databases</dt><dd>${counts.dbs}</dd></div>
    <div><dt>Generated</dt><dd>${htmlEscape(formattedDate)}</dd></div>
  </dl>
  <a class="index-stats-card" href="stats.html">
    <span class="index-stats-card-icon" aria-hidden="true">📊</span>
    <span class="index-stats-card-text">
      <span class="index-stats-card-title">Workspace statistics</span>
      <span class="index-stats-card-sub">Edit activity, block-type mix, top-edited pages &amp; more</span>
    </span>
    <span class="index-stats-card-arrow" aria-hidden="true">→</span>
  </a>
  ${searchBox}
</header>
<section class="index-tree">
  <h2 class="section-title">Contents</h2>
  <nav class="tree-root">${renderTree(tree).replace(/(src|href)="assets[\\/]/g, '$1="../assets/')}</nav>
</section>
${renderFooter()}
`;
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${htmlEscape(titleForTab(archiveTitle))}</title>
${favicon}
<link rel="stylesheet" href="${STYLE_FILENAME}">
<link rel="stylesheet" href="${KATEX_CSS_FILENAME}">
<script>try{var t=localStorage.getItem('ne-theme');if(t==='dark'||t==='light')document.documentElement.setAttribute('data-theme',t);}catch(e){}</script>
</head>
<body class="index"><div class="layout index">${body}</div>
${searchTags}
</body>
</html>
`;
  const abs = path.join(htmlDir, "index.html");
  await fsp.writeFile(abs, html);
  return abs;
}
